/* =========================================================
   SEARCH PAGE MEDIA ENGINE
========================================================= */

/*
   The existing search.html creates the cards itself.

   This observer watches those cards and automatically
   changes the media area according to the product type.

   Therefore your search.html does NOT need a complicated
   product rendering system.
*/


(function(){

    /* =====================================================
       ADD SEARCH MEDIA CSS
    ===================================================== */

    const style = document.createElement("style");

    style.textContent = `

        .search-media{
            width:100%;
            height:280px;
            position:relative;
            overflow:hidden;
            background:#f2f2f2;
        }

        .search-media > img,
        .search-media > video{
            width:100%;
            height:280px;
            display:block;
            object-fit:cover;
            background:#f2f2f2;
        }

        .search-slider{
            width:100%;
            height:280px;
            position:relative;
            overflow:hidden;
            background:#f2f2f2;
        }

        .search-slide{
            width:100%;
            height:280px;
            object-fit:cover;
            display:none;
        }

        .search-slide.active{
            display:block;
        }

        .search-slider-btn{
            position:absolute;
            top:50%;
            transform:translateY(-50%);

            width:38px;
            height:38px;

            border:none;
            border-radius:50%;

            background:rgba(0,0,0,0.55);
            color:#fff;

            font-size:20px;
            line-height:38px;

            cursor:pointer;

            z-index:10;

            transition:0.2s;
        }

        .search-slider-btn:hover{
            background:rgba(0,0,0,0.8);
        }

        .search-slider-btn.prev{
            left:10px;
        }

        .search-slider-btn.next{
            right:10px;
        }

        .search-media video{
            object-fit:cover;
        }

    `;

    document.head.appendChild(style);


    /* =====================================================
       GET PRODUCT FROM LINK
    ===================================================== */

    function getProductFromCard(card){

        const link =
            card.querySelector(".view-product");

        if(!link){
            return null;
        }

        const match =
            link.href.match(/[?&]id=(\d+)/);

        if(!match){
            return null;
        }

        const id =
            Number(match[1]);

        return searchProducts.find(
            product => product.id === id
        );

    }


    /* =====================================================
       CREATE VIDEO
    ===================================================== */

    function createVideo(media, slider = false){

        const video =
            document.createElement("video");

        video.src =
            media.src;

        video.playsInline = true;

        video.preload = "metadata";

        if(slider){

            video.autoplay = true;
            video.muted = true;
            video.loop = true;

            video.setAttribute(
                "autoplay",
                ""
            );

            video.setAttribute(
                "muted",
                ""
            );

            video.setAttribute(
                "loop",
                ""
            );

            video.setAttribute(
                "playsinline",
                ""
            );

        }else{

            video.controls = true;

            video.setAttribute(
                "controls",
                ""
            );

        }

        return video;

    }


    /* =====================================================
       CREATE SINGLE MEDIA
    ===================================================== */

    function createSingleMedia(product){

        const wrapper =
            document.createElement("div");

        wrapper.className =
            "search-media";


        const media =
            product.media[0];


        if(media.type === "video"){

            const video =
                createVideo(media, false);

            wrapper.appendChild(video);

        }else{

            const img =
                document.createElement("img");

            img.src =
                media.src;

            img.alt =
                product.name;

            wrapper.appendChild(img);

        }


        return wrapper;

    }


    /* =====================================================
       CREATE SLIDER
    ===================================================== */

    function createSlider(product){

        const slider =
            document.createElement("div");

        slider.className =
            "search-slider";


        const slides = [];


        product.media.forEach(
            (media, index) => {

                let element;


                if(media.type === "video"){

                    element =
                        createVideo(media, true);

                }else{

                    element =
                        document.createElement("img");

                    element.src =
                        media.src;

                    element.alt =
                        product.name;

                }


                element.classList.add(
                    "search-slide"
                );


                if(index === 0){

                    element.classList.add(
                        "active"
                    );

                }


                slider.appendChild(element);

                slides.push(element);

            }
        );


        /* =================================================
           PREVIOUS BUTTON
        ================================================= */

        const prev =
            document.createElement("button");

        prev.className =
            "search-slider-btn prev";

        prev.type =
            "button";

        prev.innerHTML =
            "❮";


        /* =================================================
           NEXT BUTTON
        ================================================= */

        const next =
            document.createElement("button");

        next.className =
            "search-slider-btn next";

        next.type =
            "button";

        next.innerHTML =
            "❯";


        slider.appendChild(prev);
        slider.appendChild(next);


        /* =================================================
           SLIDER FUNCTION
        ================================================= */

        let current =
            0;


        function showSlide(index){

            if(!slides.length){
                return;
            }


            slides.forEach(
                (slide, i) => {

                    slide.classList.toggle(
                        "active",
                        i === index
                    );


                    if(
                        slide.tagName ===
                        "VIDEO"
                    ){

                        if(i === index){

                            slide.currentTime = 0;

                            slide.play().catch(
                                () => {}
                            );

                        }else{

                            slide.pause();

                        }

                    }

                }
            );

        }


        prev.addEventListener(
            "click",
            function(event){

                event.preventDefault();

                event.stopPropagation();


                current--;

                if(current < 0){

                    current =
                        slides.length - 1;

                }


                showSlide(current);

            }
        );


        next.addEventListener(
            "click",
            function(event){

                event.preventDefault();

                event.stopPropagation();


                current++;

                if(
                    current >=
                    slides.length
                ){

                    current = 0;

                }


                showSlide(current);

            }
        );


        return slider;

    }


    /* =====================================================
       BUILD CORRECT MEDIA
    ===================================================== */

    function fixProductCard(card){

        if(
            card.dataset.mediaFixed ===
            "true"
        ){
            return;
        }


        const product =
            getProductFromCard(card);


        if(!product){
            return;
        }


        const oldImage =
            card.querySelector(
                ".product-image"
            );


        if(!oldImage){
            return;
        }


        let mediaElement;


        if(
            product.type ===
            "slider"
        ){

            mediaElement =
                createSlider(product);

        }else{

            mediaElement =
                createSingleMedia(product);

        }


        oldImage.replaceWith(
            mediaElement
        );


        card.dataset.mediaFixed =
            "true";

    }


    /* =====================================================
       WATCH FOR SEARCH RESULTS
    ===================================================== */

    function processCards(){

        const cards =
            document.querySelectorAll(
                "#productsGrid .product-card"
            );


        cards.forEach(
            card => {

                fixProductCard(card);

            }
        );

    }


    /* =====================================================
       MUTATION OBSERVER
    ===================================================== */

    const observer =
        new MutationObserver(
            function(){

                processCards();

            }
        );


    /* =====================================================
       START OBSERVER WHEN PAGE IS READY
    ===================================================== */

    function start(){

        const grid =
            document.getElementById(
                "productsGrid"
            );


        if(!grid){

            setTimeout(
                start,
                50
            );

            return;

        }


        observer.observe(
            grid,
            {
                childList:true,
                subtree:true
            }
        );


        processCards();

    }


    if(
        document.readyState ===
        "loading"
    ){

        document.addEventListener(
            "DOMContentLoaded",
            start
        );

    }else{

        start();

    }

})();
